"""Small-memory rational export of two membrane models; standard library only."""
from fractions import Fraction as F
from itertools import product
from pathlib import Path
import hashlib
import json

HERE=Path(__file__).resolve().parent
I=tuple(tuple(F(i==j) for j in range(3)) for i in range(3))
Z=((F(0),F(-1),F(0)),(F(1),F(0),F(0)),(F(0),F(0),F(1)))
Q=tuple(tuple(F(x,125) for x in row) for row in ((53,-60,96),(60,-75,-80),(96,80,-3)))

def mul(a,b):
    return tuple(tuple(sum(a[i][k]*b[k][j] for k in range(3)) for j in range(3)) for i in range(3))
def transpose(a):return tuple(zip(*a))
def vector(a,x):return tuple(sum(a[i][j]*x[j] for j in range(3)) for i in range(3))
def scale(a,r):return tuple(tuple(r*x for x in row) for row in a)
def det(a):
    return a[0][0]*(a[1][1]*a[2][2]-a[1][2]*a[2][1])-a[0][1]*(a[1][0]*a[2][2]-a[1][2]*a[2][0])+a[0][2]*(a[1][0]*a[2][1]-a[1][1]*a[2][0])

def recipe(q,wing=None):
    result=[]
    for a,b in product((-1,1),repeat=2):
        result.append((scale(I,F(1,2)),(F(a,2),F(b,2),F(0)),F(1,2),'square',None))
    orbit=[];z=I
    for k in range(4):
        rotation=mul(mul(z,Q),transpose(z));point=vector(z,(F(1),F(1),F(0)))
        orbit.append((rotation,point));z=mul(Z,z)
        result.append((scale(rotation,q),(F(0),)*3,q,'core',(F(0),)*3))
    if wing is not None:
        for rotation,point in orbit:
            mat=scale(rotation,wing);mapped=vector(mat,point)
            shift=tuple(a-b for a,b in zip(point,mapped))
            result.append((mat,shift,wing,'wing',point))
    return result

def verify(maps):
    for matrix,shift,r,kind,anchor in maps:
        assert 0<r<1
        assert mul(transpose(matrix),matrix)==scale(I,r*r)
        assert det(matrix)==r**3
        if anchor is not None:
            assert tuple(a+b for a,b in zip(vector(matrix,anchor),shift))==anchor
    permutation=[]
    for matrix,shift,*_ in maps:
        a=mul(mul(Z,matrix),transpose(Z));t=vector(Z,shift)
        matches=[j for j,(m,b,*_) in enumerate(maps) if m==a and b==t]
        assert len(matches)==1;permutation.append(matches[0])
    return permutation

def encode(maps):
    return [dict(id=f'f{i}',kind=kind,contraction=str(r),
                 linear=[[str(x) for x in row] for row in matrix],
                 translation=[str(x) for x in shift],
                 fixed_anchor=None if anchor is None else [str(x) for x in anchor])
            for i,(matrix,shift,r,kind,anchor) in enumerate(maps)]

def block(identifier,name,maps,camera):
    out=['@'+identifier,'$n='+name,'$dim=3']
    for i,(matrix,shift,*_) in enumerate(maps):
        out.append(f'f{i}=['+','.join(map(str,shift))+']*['+','.join(str(x) for row in matrix for x in row)+']')
    out.append('$camera='+camera)
    out.append('K=('+'|'.join(f'f{i}' for i in range(len(maps)))+')*K')
    return '\n'.join(out)

def main():
    assert mul(transpose(Q),Q)==I and det(Q)==1
    a=recipe(F(1,4));b=recipe(F(1,10),F(9,20))
    permutation_a,permutation_b=verify(a),verify(b)
    source=('# Two exact rational spatial membrane candidates.\n'
            '# Generated by export_exact.py; no rounded coefficients.\n'
            '# Established properties and limits: MEMBRANE.md and CORONA.md.\n'
            '# Historical novelty and exact Hausdorff dimension unresolved.\n\n'+
            block('MembraneBasic4','Membrane - q 1/4 - 8 exact similarities',a,'[[4,-6,3],[0,0,0],[0,0,1],36]')+'\n\n'+
            block('MembraneCoronaSlant9_20','Anchored membrane - q 1/10 r 9/20 - 12 exact similarities',b,'[[5,-7,-3],[0,0,-1/4],[0,0,1],36]')+'\n')
    target=HERE/'Membrane-and-Anchored-Slant-Exact.aifs';target.write_text(source,encoding='utf-8')
    data={
        'definition':'F(x)=linear*x+translation; all strings are exact rational numbers',
        'symmetry_generator':[[str(x) for x in row] for row in Z],
        'rotation_generator':[[str(x) for x in row] for row in Q],
        'models':[
            {'id':'MembraneBasic4','q':'1/4','wing':None,'maps':encode(a),'C4_permutation':permutation_a,
             'cubed_ratio_sum':str(sum(r**3 for _,_,r,*_ in a))},
            {'id':'MembraneCoronaSlant9_20','q':'1/10','wing':'9/20','maps':encode(b),'C4_permutation':permutation_b,
             'cubed_ratio_sum':str(sum(r**3 for _,_,r,*_ in b))}]}
    (HERE/'membrane-exact-recipes.json').write_text(json.dumps(data,indent=2)+'\n',encoding='utf-8')
    receipt={'aifs_file':target.name,'sha256':hashlib.sha256(target.read_bytes()).hexdigest(),
             'blocks':2,'map_counts':[len(a),len(b)],'coefficient_type':'exact rationals',
             'checks':['all 20 similarity equations exactly in Fraction arithmetic',
                       'all 20 positive determinants equal contraction cubed',
                       'all core and wing anchors fixed exactly',
                       'C4 conjugation permutes each model exactly'],
             'aifs_syntax_source':'https://github.com/mekhontsev/ifstile/blob/master/manual.md',
             'native_application_import':'not tested by exporter; root will inspect',
             'memory_use':'standard library only; twenty 3x3 matrices, no dense geometry'}
    (HERE/'membrane-aifs-receipt.json').write_text(json.dumps(receipt,indent=2)+'\n',encoding='utf-8')
    print(json.dumps(receipt,indent=2))

if __name__=='__main__':main()
