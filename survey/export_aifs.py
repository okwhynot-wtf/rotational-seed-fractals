"""Exact radical AIFS export, independently reconstructed with SymPy.

Syntax follows https://ifstile.com/manual/: row-major matrix, translation
composed on the left, and K=(f0|...|fn)*K.
"""
from pathlib import Path
import json
import re
import argparse
import sympy as s
import numpy as np
from model import ROOT,construct

def rotation(axis,tangent):
    v=s.Matrix(axis);v=v/s.sqrt(v.dot(v));q=s.Rational(tangent)
    c=(1-q*q)/(1+q*q);sn=2*q/(1+q*q);x,y,z=v
    skew=s.Matrix([[0,-z,y],[z,0,-x],[-y,x,0]])
    return c*s.eye(3)+(1-c)*v*v.T+sn*skew

def frame(v):
    v=s.Matrix(v);v=v/s.sqrt(v.dot(v))
    k=min(range(3),key=lambda j:abs(v[j]));helper=s.eye(3)[:,k]
    w=v.cross(helper);w=w/s.sqrt(w.dot(w))
    return s.Matrix.hstack(v,w,v.cross(w))

def exact_maps(m=3,M=2,central_scale='1/4'):
    B=s.Matrix([1,1,1]);G=s.Matrix([[0,0,1],[1,0,0],[0,1,0]])
    out=[]
    for j in range(M):
        roll=s.Rational(2*j+1-M,3*(M-1))
        offset=s.Rational(2*j+1-M,M)
        out.append((rotation(B,roll)/M,offset*B))
    corners=list(map(s.Matrix,[[-2,-1,0],[2,-1,0],[2,1,0],[-2,1,0]]))
    rings=[]
    for u,v in zip(corners,corners[1:]+corners[:1]):
        count=int(s.sqrt((v-u).dot(v-u))*m)
        for j in range(count):rings.append((u+(v-u)*s.Rational(j,count),u+(v-u)*s.Rational(j+1,count)))
    bridges=[(B+s.Matrix([0,0,-s.Rational(j,m)]),B+s.Matrix([0,0,-s.Rational(j+1,m)])) for j in range(m)]
    for edges in (rings,bridges):
        for orbit in range(3):
            U=G**orbit
            for a,b in edges:
                r=s.sqrt((b-a).dot(b-a))/s.sqrt(12)
                Q=frame(b-a)*rotation([1,0,0],s.Rational(1,2))*frame(2*B).T
                out.append((s.simplify(r*U*Q*U.T),s.simplify(U*(a+b)/2)))
    q=s.Rational(central_scale)
    out.append((q*s.eye(3),s.zeros(3,1)))
    for i in range(3):out.append((q*rotation(s.eye(3)[:,i],s.Rational(1,2)),s.zeros(3,1)))
    return out

def aifs_expr(x):
    x=s.simplify(x)
    result=str(x).replace('**','^')
    return re.sub(r'sqrt\((\d+)\)',r'\1^(1/2)',result)

def main():
    parser=argparse.ArgumentParser();parser.add_argument('--m',type=int,default=3)
    parser.add_argument('--axis',type=int,default=2);parser.add_argument('--central',default='1/4')
    args=parser.parse_args();m,axis=args.m,args.axis
    maps=exact_maps(m,axis,args.central);d=construct(m,overlap=True,axis_subdivisions=axis,central_scale=args.central)
    lines=[f'# Exact radical Borromean C3 interval-backed continuum, m={m}, M={axis}, q={args.central}.',
           '# Generated by export_aifs.py. No rounded matrix coefficients.',
           '# Research candidate; historical novelty and exact dim_H unresolved.',
           '@BorromeanC3',f'$n=Borromean C3 - {len(maps)} exact similarities','$dim=3']
    maxerr=0.
    for i,((M,t),num) in enumerate(zip(maps,d['maps'])):
        r2=s.Rational(1,axis*axis) if num['kind']=='axis' else s.Rational(args.central)**2 if num['kind']=='overlap' else s.Rational(1,12*m*m)
        assert s.simplify(M.T*M-r2*s.eye(3))==s.zeros(3)
        maxerr=max(maxerr,float(np.max(abs(np.array(M.evalf(),float)-num['r']*np.array(num['R'])))),
                   float(np.max(abs(np.array(t.evalf(),float).ravel()-num['t']))))
        lines.append(f'f{i}=['+','.join(aifs_expr(x) for x in t)+']*['+','.join(aifs_expr(x) for x in M)+']')
    assert maxerr<1e-14 and len(maps)==39*m+axis+4
    lines+=['$camera=[[4,-6,4],[0,0,0],[0,0,1],36]',
            'K=('+'|'.join(f'f{i}' for i in range(len(maps)))+')*K','']
    stem=f'Borromean-C3-M{m}-Exact' if axis==2 and args.central=='1/4' else f'Borromean-C3-m{m}-axis{axis}-q{args.central.replace("/","_")}-Exact'
    target=ROOT/(stem+'.aifs');target.write_text('\n'.join(lines))
    receipt={'file':target.name,'maps':len(maps),'coefficient_definition':'exact radicals and rationals',
             'symbolic_similarity_checks':'passed for all maps','max_difference_from_numerical_model':maxerr,
             'native_application_import':'not yet tested; root to inspect',
             'syntax_source':'https://ifstile.com/manual/'}
    receipt_name='aifs_export_receipt.json' if axis==2 and args.central=='1/4' else stem+'-receipt.json'
    (ROOT/receipt_name).write_text(json.dumps(receipt,indent=2)+'\n')
    print(json.dumps(receipt,indent=2))

if __name__=='__main__':main()
